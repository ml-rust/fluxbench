//! HTML page assembly: header, summary, charts, and per-group result tables.

use super::chart::render_chart;
use super::escape::escape;
use super::options::{HtmlGroup, HtmlOptions};
use super::style::{BASE_CSS, theme_vars};
use crate::format_duration;
use crate::report::{BenchmarkReportResult, BenchmarkStatus, Report};
use std::collections::BTreeMap;
use std::fmt::Write;

/// Generate the HTML report with default options.
pub fn generate_html_report(report: &Report) -> String {
    generate_html_report_with(report, &HtmlOptions::default())
}

/// Generate a single-file HTML report with inline CSS and SVG. It has no scripts.
pub fn generate_html_report_with(report: &Report, options: &HtmlOptions) -> String {
    let mut html = String::with_capacity(64 * 1024);
    let title = escape(&options.title);

    html.push_str("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n");
    html.push_str("  <meta charset=\"UTF-8\">\n");
    html.push_str("  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">\n");
    let _ = writeln!(
        html,
        "  <title>{title} - {}</title>",
        report.meta.timestamp.format("%Y-%m-%d")
    );
    html.push_str("  <style>\n");
    html.push_str(theme_vars(options.theme));
    html.push_str(BASE_CSS);
    html.push_str("  </style>\n</head>\n<body>\n");

    write_header(&mut html, report, options, &title);
    html.push_str("  <main>\n");
    write_summary(&mut html, report);
    if !options.charts.is_empty() {
        write_charts(&mut html, report, options);
    }
    write_results(&mut html, report, &options.groups);
    html.push_str("  </main>\n");

    let _ = writeln!(
        html,
        "  <footer><p>Generated by FluxBench v{}</p></footer>",
        env!("CARGO_PKG_VERSION")
    );
    html.push_str("</body>\n</html>\n");
    html
}

fn write_header(html: &mut String, report: &Report, options: &HtmlOptions, title: &str) {
    html.push_str("  <header>\n");
    let _ = writeln!(html, "    <h1>{title}</h1>");
    if !options.description.is_empty() {
        let _ = writeln!(
            html,
            "    <p class=\"description\">{}</p>",
            escape(&options.description)
        );
    }
    let _ = writeln!(
        html,
        "    <div class=\"meta\">\n      <span>Commit: {}</span>\n      <span>Branch: {}</span>\n      <span>{}</span>\n    </div>",
        escape(report.meta.git_commit.as_deref().unwrap_or("unknown")),
        escape(report.meta.git_branch.as_deref().unwrap_or("unknown")),
        report.meta.timestamp.format("%Y-%m-%d %H:%M:%S UTC")
    );
    html.push_str("  </header>\n");
}

fn write_summary(html: &mut String, report: &Report) {
    let _ = writeln!(
        html,
        "    <section id=\"summary\">\n      <h2>Summary</h2>\n      <div class=\"stats-grid\">\n        <div class=\"stat passed\">{} Passed</div>\n        <div class=\"stat failed\">{} Failed</div>\n        <div class=\"stat crashed\">{} Crashed</div>\n        <div class=\"stat skipped\">{} Skipped</div>\n      </div>\n    </section>",
        report.summary.passed,
        report.summary.failed,
        report.summary.crashed,
        report.summary.skipped
    );
}

fn write_charts(html: &mut String, report: &Report, options: &HtmlOptions) {
    let (rows, cols) = (options.grid.0.max(1), options.grid.1.max(1));
    let _ = writeln!(
        html,
        "    <section id=\"charts\">\n      <h2>Charts</h2>\n      <div class=\"chart-grid\" style=\"grid-template-columns: repeat({cols}, minmax(0, 1fr)); grid-template-rows: repeat({rows}, auto);\">"
    );
    for chart in &options.charts {
        let placement = chart
            .position
            .map(|(r, c)| format!(" style=\"grid-row: {r}; grid-column: {c};\""))
            .unwrap_or_default();
        let _ = writeln!(
            html,
            "        <figure class=\"chart\"{placement}>\n          <figcaption>{} ({})</figcaption>\n{}        </figure>",
            escape(&chart.title),
            escape(&chart.metric),
            render_chart(chart, report, options.chart_width, options.chart_height)
        );
    }
    html.push_str("      </div>\n    </section>\n");
}

fn write_results(html: &mut String, report: &Report, groups: &[HtmlGroup]) {
    html.push_str("    <section id=\"results\">\n      <h2>Benchmark Results</h2>\n");
    if report.results.is_empty() {
        html.push_str("      <p>No benchmarks ran.</p>\n");
    }

    // Sections sort by group path, so a parent comes before its children.
    let mut sections: BTreeMap<Vec<&str>, Vec<&BenchmarkReportResult>> = BTreeMap::new();
    for result in &report.results {
        sections
            .entry(group_path(&result.group, groups))
            .or_default()
            .push(result);
    }

    for (path, results) in sections {
        let Some(&id) = path.last() else { continue };
        let _ = writeln!(
            html,
            "      <section class=\"group\" id=\"group-{}\">\n        <h3>{}</h3>",
            escape(id),
            escape(&path.join(" / "))
        );
        if let Some(def) = groups.iter().find(|g| g.id == id) {
            if !def.description.is_empty() {
                let _ = writeln!(
                    html,
                    "        <p class=\"group-desc\">{}</p>",
                    escape(&def.description)
                );
            }
            if !def.tags.is_empty() {
                let _ = writeln!(
                    html,
                    "        <p class=\"group-tags\">Tags: {}</p>",
                    escape(&def.tags.join(", "))
                );
            }
        }
        html.push_str("        <div class=\"table-wrap\"><table class=\"results-table\">\n");
        html.push_str("          <thead><tr><th>Benchmark</th><th>Mean</th><th>p99</th><th>Alloc/iter</th><th>Status</th><th>Note</th></tr></thead>\n          <tbody>\n");
        for result in results {
            write_row(html, result);
        }
        html.push_str("          </tbody>\n        </table></div>\n      </section>\n");
    }
    html.push_str("    </section>\n");
}

fn write_row(html: &mut String, result: &BenchmarkReportResult) {
    let (mean, p99, alloc) = match &result.metrics {
        Some(m) => (
            format_duration(m.mean_ns),
            format_duration(m.p99_ns),
            format!("{} B / {}", m.alloc_bytes, m.alloc_count),
        ),
        None => ("-".to_string(), "-".to_string(), "-".to_string()),
    };
    let status = match result.status {
        BenchmarkStatus::Passed => "passed",
        BenchmarkStatus::Failed => "failed",
        BenchmarkStatus::Crashed => "crashed",
        BenchmarkStatus::Skipped => "skipped",
    };
    let note = result
        .failure
        .as_ref()
        .map(|f| format!("{}: {}", f.kind, f.message))
        .unwrap_or_default();
    let _ = writeln!(
        html,
        "            <tr><td>{}</td><td>{mean}</td><td>{p99}</td><td>{alloc}</td><td class=\"status-{status}\">{status}</td><td>{}</td></tr>",
        escape(&result.id),
        escape(&note)
    );
}

/// Group IDs from the root ancestor down to `id`. A parent cycle stops the walk.
fn group_path<'a>(id: &'a str, groups: &'a [HtmlGroup]) -> Vec<&'a str> {
    let mut path = vec![id];
    let mut current = id;
    while let Some(parent) = groups
        .iter()
        .find(|g| g.id == current)
        .and_then(|g| g.parent.as_deref())
    {
        if path.contains(&parent) {
            break;
        }
        path.push(parent);
        current = parent;
    }
    path.reverse();
    path
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::html::options::{HtmlChart, HtmlTheme};
    use fluxbench_core::ChartType;

    fn report_json() -> Report {
        let metrics = |mean: f64| {
            serde_json::json!({
                "samples": 2, "mean_ns": mean, "median_ns": mean, "std_dev_ns": 1.0,
                "min_ns": mean, "max_ns": mean, "p50_ns": mean, "p90_ns": mean, "p95_ns": mean,
                "p99_ns": mean, "p999_ns": mean, "skewness": 0.0, "kurtosis": 3.0,
                "ci_level": 0.95, "throughput_ops_sec": null, "alloc_bytes": 0,
                "alloc_count": 0, "mean_cycles": 0.0, "median_cycles": 0.0,
                "min_cycles": 0, "max_cycles": 0, "cycles_per_ns": 0.0
            })
        };
        let result = |id: &str, group: &str, mean: f64| {
            serde_json::json!({
                "id": id, "name": id, "group": group, "status": "passed",
                "severity": "Info", "file": "f.rs", "line": 1,
                "metrics": metrics(mean), "threshold": 0.0,
                "comparison": null, "failure": null
            })
        };
        serde_json::from_value(serde_json::json!({
            "meta": {
                "schema_version": 2, "version": "0", "timestamp": "2026-01-01T00:00:00Z",
                "git_commit": null, "git_branch": null,
                "system": { "os": "linux", "os_version": "6", "cpu": "x", "cpu_cores": 1, "memory_gb": 1.0 },
                "config": {
                    "warmup_time_ns": 0, "measurement_time_ns": 0, "min_iterations": null,
                    "max_iterations": null, "sample_count": 2, "iters_per_sample": null,
                    "bootstrap_iterations": 0, "confidence_level": 0.95,
                    "track_allocations": false, "timer_overhead_ns": 0.0
                }
            },
            "results": [
                result("child_bench", "json_parsing", 200.0),
                result("<script>", "parsing", 100.0)
            ],
            "comparisons": [], "comparison_series": [], "synthetics": [], "verifications": [],
            "summary": {
                "total_benchmarks": 2, "passed": 2, "failed": 0, "crashed": 0, "skipped": 0,
                "regressions": 0, "improvements": 0, "critical_failures": 0, "warnings": 0,
                "total_duration_ms": 1.0
            }
        }))
        .unwrap()
    }

    fn options() -> HtmlOptions {
        HtmlOptions {
            title: "Nightly & Co".to_string(),
            description: "Parser suite".to_string(),
            theme: HtmlTheme::Dark,
            chart_width: 640,
            chart_height: 360,
            grid: (1, 2),
            groups: vec![
                HtmlGroup {
                    id: "parsing".to_string(),
                    description: "All parsers".to_string(),
                    tags: vec!["hot".to_string()],
                    parent: None,
                },
                HtmlGroup {
                    id: "json_parsing".to_string(),
                    description: String::new(),
                    tags: Vec::new(),
                    parent: Some("parsing".to_string()),
                },
            ],
            charts: vec![HtmlChart {
                title: "Means".to_string(),
                kind: ChartType::Bar,
                metric: "mean".to_string(),
                benchmarks: vec!["child_bench".to_string(), "missing".to_string()],
                target: Some(150.0),
                position: Some((1, 2)),
            }],
        }
    }

    #[test]
    fn title_description_and_theme_come_from_options() {
        let html = generate_html_report_with(&report_json(), &options());
        assert!(html.contains("<h1>Nightly &amp; Co</h1>"));
        assert!(html.contains("<p class=\"description\">Parser suite</p>"));
        assert!(html.contains("--bg-primary: #111827"));
        assert!(!html.contains("<script>"));
        assert!(html.contains("&lt;script&gt;"));
    }

    #[test]
    fn groups_nest_under_parent_path() {
        let html = generate_html_report_with(&report_json(), &options());
        let parent = html.find("<h3>parsing</h3>").unwrap();
        let child = html.find("<h3>parsing / json_parsing</h3>").unwrap();
        assert!(parent < child);
        assert!(html.contains("All parsers"));
        assert!(html.contains("Tags: hot"));
    }

    #[test]
    fn chart_renders_svg_with_bars_target_and_missing_note() {
        let html = generate_html_report_with(&report_json(), &options());
        assert!(html.contains("grid-template-columns: repeat(2, minmax(0, 1fr))"));
        assert!(html.contains("grid-row: 1; grid-column: 2;"));
        assert!(html.contains("width=\"640\" height=\"360\""));
        assert_eq!(html.matches("<rect class=\"bar\"").count(), 1);
        assert!(html.contains("missing (no data)"));
        assert!(html.contains("class=\"target\""));
    }

    #[test]
    fn line_chart_draws_polyline() {
        let mut opts = options();
        opts.charts[0].kind = ChartType::Line;
        opts.charts[0].benchmarks = vec!["<script>".to_string(), "child_bench".to_string()];
        let html = generate_html_report_with(&report_json(), &opts);
        assert!(html.contains("<polyline class=\"line\""));
        assert_eq!(html.matches("<circle class=\"point\"").count(), 2);
    }

    #[test]
    fn empty_report_is_a_valid_page() {
        let mut report = report_json();
        report.results.clear();
        let html = generate_html_report(&report);
        assert!(html.contains("<h1>FluxBench Report</h1>"));
        assert!(html.contains("No benchmarks ran."));
        assert!(html.ends_with("</html>\n"));
    }

    #[test]
    fn every_report_string_is_escaped() {
        let evil = "<img src=x onerror=1>&\"'";
        let escaped = "&lt;img src=x onerror=1&gt;&amp;&quot;&#39;";
        let mut report = report_json();
        report.meta.git_commit = Some(evil.to_string());
        report.meta.git_branch = Some(evil.to_string());
        report.results[0].id = evil.to_string();
        report.results[0].group = evil.to_string();
        report.results[0].status = BenchmarkStatus::Failed;
        report.results[0].failure = Some(crate::report::FailureInfo {
            kind: evil.to_string(),
            message: evil.to_string(),
            backtrace: None,
            signal: None,
        });
        let mut opts = options();
        opts.title = evil.to_string();
        opts.description = evil.to_string();
        opts.groups.push(HtmlGroup {
            id: evil.to_string(),
            description: evil.to_string(),
            tags: vec![evil.to_string()],
            parent: None,
        });
        opts.charts[0].title = evil.to_string();
        opts.charts[0].metric = evil.to_string();
        opts.charts[0].benchmarks = vec![evil.to_string()];
        let html = generate_html_report_with(&report, &opts);
        assert!(!html.contains("<img"));
        assert!(!html.contains(evil));
        assert!(html.contains(&format!("<span>Commit: {escaped}</span>")));
        assert!(html.contains(&format!("<span>Branch: {escaped}</span>")));
        assert!(html.contains(&format!("id=\"group-{escaped}\"")));
        assert!(html.contains(&format!("<td>{escaped}</td>")));
        assert!(html.contains(&format!("{escaped}: {escaped}")));
        assert!(html.contains(&format!("<p class=\"group-desc\">{escaped}</p>")));
        assert!(html.contains(&format!("Tags: {escaped}")));
        assert!(html.contains(&format!("<figcaption>{escaped} ({escaped})</figcaption>")));
    }

    #[test]
    fn page_has_summary_and_group_sections() {
        let html = generate_html_report_with(&report_json(), &options());
        assert!(html.starts_with("<!DOCTYPE html>"));
        assert!(html.contains("<div class=\"stat passed\">2 Passed</div>"));
        assert!(html.contains("<section class=\"group\" id=\"group-parsing\">"));
        assert!(html.contains("<section class=\"group\" id=\"group-json_parsing\">"));
        assert!(html.contains("<td class=\"status-passed\">passed</td>"));
        assert!(html.contains("Generated by FluxBench v"));
    }
}
